int	ft_sqrt(int nb)
{
	int	i;

	if (nb < 1)
		return (0);
	i = 1;
	while (i <= nb / i)
	{
		if (i == nb / i && i * i == nb)
			return (i);
		i++;
	}
	return (0);
}
